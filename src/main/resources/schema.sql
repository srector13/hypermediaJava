-- Shared by the JDBC and JPA stores. Hibernate does not generate DDL (ddl-auto: none).
CREATE TABLE IF NOT EXISTS employee (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  VARCHAR(60)    NOT NULL,
    last_name   VARCHAR(60)    NOT NULL,
    email       VARCHAR(160)   NOT NULL,
    department  VARCHAR(20)    NOT NULL,
    title       VARCHAR(80)    NOT NULL,
    location    VARCHAR(60)    NOT NULL,
    salary      NUMERIC(12, 2) NOT NULL,
    hire_date   DATE           NOT NULL,
    status      VARCHAR(20)    NOT NULL,
    version     BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_employee_email UNIQUE (email)
);

-- Every sortable column gets an index ending in id, matching the ORDER BY ... , id tiebreaker.
CREATE INDEX IF NOT EXISTS ix_employee_name       ON employee (last_name, first_name, id);
CREATE INDEX IF NOT EXISTS ix_employee_keyset     ON employee (last_name, id);
CREATE INDEX IF NOT EXISTS ix_employee_department ON employee (department, id);
CREATE INDEX IF NOT EXISTS ix_employee_status     ON employee (status, id);
CREATE INDEX IF NOT EXISTS ix_employee_salary     ON employee (salary, id);
CREATE INDEX IF NOT EXISTS ix_employee_hire_date  ON employee (hire_date, id);
CREATE INDEX IF NOT EXISTS ix_employee_title      ON employee (title, id);
CREATE INDEX IF NOT EXISTS ix_employee_location   ON employee (location, id);
